"""Standard-library helpers shared by host commands."""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import uuid

ROOT = Path(__file__).resolve().parent


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def write_json(path, value):
    with Path(path).open("x") as f:
        f.write(json.dumps(value, indent=2) + "\n")


def image_id(tag):
    return subprocess.check_output(
        ["docker", "image", "inspect", "--format", "{{.Id}}", tag], text=True, timeout=30).strip()


def container_flags(name, network, work, memory="2g", cpus="1", pids=128):
    uid, gid = os.getuid(), os.getgid()
    if not uid:
        raise RuntimeError("run the harness as a non-root user with Docker access")
    return ["docker", "run", "--rm", "--init", "--name", name,
            "--label", "quality.harness=pi-0.86.1", "--network", network,
            "--user", f"{uid}:{gid}", "--read-only", "--cap-drop", "ALL",
            "--security-opt", "no-new-privileges", "--memory", memory,
            "--memory-swap", memory, "--cpus", cpus, "--pids-limit", str(pids),
            "--ulimit", "nofile=1024:1024", "--ulimit", "fsize=268435456:268435456",
            "--tmpfs", "/tmp:rw,nosuid,nodev,noexec,size=256m,mode=1777",
            "--tmpfs", f"/home/agent:rw,nosuid,nodev,size=128m,mode=700,uid={uid},gid={gid}",
            "--mount", f"type=bind,src={Path(work).resolve()},dst=/work",
            "--workdir", "/work", "--env", "HOME=/home/agent",
            "--env", "PYTHONDONTWRITEBYTECODE=1"]


def stop_owned(name):
    # Only names freshly generated by this invocation are accepted by callers.
    subprocess.run(["docker", "stop", "--time", "2", name],
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=15)


def unique_name(kind):
    return "quality-" + kind + "-" + uuid.uuid4().hex[:16]
